export function roleFromLabels(labels = []) {
  if (labels.includes(ROLES.ADMIN)) return ROLES.ADMIN
  if (labels.includes(ROLES.DEPARTMENT)) return ROLES.DEPARTMENT
  return ROLES.STUDENT
}

/**
 * Row permissions for complaints and history: administrators read. NOT the student: students get their data through this
 * function's whitelisted views, so a field added to the row later can never leak to them through a direct read.
 */
export const complaintPermissions = () => ['read("label:admin")']
/** Permissions for the attachment once the complaint exists: read-only. Students can no longer replace or delete the evidence. */
export const lockedFilePermissions = (studentId) => [`read("user:${studentId}")`, 'read("label:admin")']

const CONTROL_CHARS = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g
const hasContent = (text) => (text.match(/[\p{L}\p{N}]/gu) ?? []).length >= 3

/** Single-line text: control characters removed, whitespace collapsed. */
const cleanLine = (value) => String(value ?? '').replace(CONTROL_CHARS, ' ').trim().replace(/\s+/g, ' ')
/** Multi-line text: control characters removed, line breaks kept (max one blank line in a row). */
const cleanBlock = (value) =>
  String(value ?? '')
    .replace(/\r\n?/g, '\n')
    .replace(CONTROL_CHARS, '')
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()

/** Validates and cleans the student's input. Throws 400 with per-field messages. */
export function validateSubmission(body) {
  const fields = {}
  const out = {}
  const isText = (value) => value === undefined || value === null || typeof value === 'string'

  if (!isText(body.title) || !isText(body.description) || !isText(body.location) || !isText(body.categoryId) || !isText(body.attachmentId)) {
    throw invalid({}, 'The complaint contains invalid data.')
  }

  const title = cleanLine(body.title)
  if (!title) fields.title = 'Enter a title for your complaint.'
  else if (title.length < RULES.title.min) fields.title = `The title must be at least ${RULES.title.min} characters.`
  else if (title.length > RULES.title.max) fields.title = `The title must be at most ${RULES.title.max} characters.`
  else if (!hasContent(title)) fields.title = 'The title must contain real words.'
  else out.title = title

  const description = cleanBlock(body.description)
  if (!description) fields.description = 'Describe your complaint.'
  else if (description.length < RULES.description.min) fields.description = `The description must be at least ${RULES.description.min} characters.`
  else if (description.length > RULES.description.max) fields.description = `The description must be at most ${RULES.description.max} characters.`
  else if (!hasContent(description)) fields.description = 'The description must contain real words.'
  else out.description = description

  const location = cleanLine(body.location)
  if (location.length > RULES.location.max) fields.location = `Location details must be at most ${RULES.location.max} characters.`
  else out.location = location || null

  const categoryId = cleanLine(body.categoryId)
  if (!categoryId) fields.categoryId = 'Choose a category.'
  else if (!ID_PATTERN.test(categoryId)) fields.categoryId = 'Choose a valid category.'
  else out.categoryId = categoryId

  const attachmentId = cleanLine(body.attachmentId)
  if (attachmentId && !ID_PATTERN.test(attachmentId)) fields.attachment = 'The attachment is not valid. Upload it again.'
  else out.attachmentId = attachmentId || null

  if (Object.keys(fields).length > 0) throw invalid(fields)
  return out
}

/** "CMP-20261122-K7M2QX": date + 6 random characters. Uniqueness is guaranteed by the database (unique row ID + index). */
export function generateReference(now, randomChars) {
  const date = now.toISOString().slice(0, 10).replaceAll('-', '')
  const chars = randomChars ?? Array.from({ length: 6 }, () => REFERENCE_ALPHABET[randomInt(REFERENCE_ALPHABET.length)]).join('')
  return `CMP-${date}-${chars}`
}

const fileExtension = (name) => {
  const match = /\.([A-Za-z0-9]{1,8})$/.exec(String(name ?? ''))
  return match ? match[1].toLowerCase() : ''
}
/** A display/download name: no path separators, no characters that are special on Windows or in HTML, no leading dots, no "..". */
const safeFileName = (name) =>
  cleanLine(String(name ?? '').replace(/[\\/:*?"<>|]/g, '_'))
    .replace(/\.{2,}/g, '.')
    .replace(/^[.\s]+/, '')
    .slice(0, 255) || 'attachment'

const attachmentOf = (row) => (row.attachmentId ? { name: row.attachmentName ?? 'attachment', mimeType: row.attachmentMime ?? '', size: row.attachmentSize ?? 0 } : null)

/**
 * What a STUDENT may see of their own complaint. An explicit whitelist: no priority, assigned staff, student IDs,
 * resolution note or anything else that is internal.
 */
export function toStudentView(row) {
  return {
    id: row.$id,
    reference: row.referenceNumber,
    title: row.title,
    description: row.description,
    location: row.location ?? '',
    categoryId: row.categoryId,
    categoryName: row.categoryName,
    departmentId: row.departmentId,
    departmentName: row.departmentName,
    status: row.status,
    submittedAt: row.submittedAt,
    attachment: attachmentOf(row),
  }
}

/** What department staff and administrators see (adds who submitted it and the priority). */
export function toComplaint(row) {
  return {
    ...toStudentView(row),
    priority: row.priority ?? 'medium',
    studentName: row.studentName,
    studentRollNumber: row.studentRollNumber ?? '',
    resolvedAt: row.resolvedAt ?? null,
    lastUpdatedByName: row.lastUpdatedByName ?? null,
    lastUpdatedAt: row.lastUpdatedAt ?? null,
  }
}

/** An internal note, for staff and administrators only. */
export const toNote = (row) => ({ id: row.$id, note: row.note, authorName: row.authorName ?? 'Staff', createdAt: row.createdAt })

/**
 * One timeline entry as sent to the browser. Students get "System"/"Department" only; staff and administrators also get the
 * name of whoever made the change. Staff user IDs are never sent.
 */
export function toTimelineEntry(entry, { staff = false } = {}) {
  const base = {
    type: entry.kind === 'remark' ? 'remark' : 'status',
    status: entry.status,
    previousStatus: entry.previousStatus ?? null,
    remark: entry.remark ?? '',
    by: entry.actorRole === 'system' ? 'System' : 'Department',
    at: entry.changedAt,
  }
  return staff ? { ...base, actorName: entry.actorName ?? base.by } : base
}

/**
 * The public status timeline, oldest first. A complaint with no stored history (or one whose first entry is missing)
 * still starts with a synthesized "submitted" entry, so tracking is never empty.
 */
export function buildTimeline(row, entries = [], options = {}) {
  const sorted = [...entries].sort((a, b) => new Date(a.changedAt) - new Date(b.changedAt))
  const timeline = sorted.map((entry) => toTimelineEntry(entry, options))
  if (timeline[0]?.status !== INITIAL_STATUS) {
    timeline.unshift(toTimelineEntry({ status: INITIAL_STATUS, actorRole: 'system', changedAt: row.submittedAt }, options))
  }
  return timeline
}

