const REMARK_CONTROL = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g
const cleanRemark = (value) => String(value ?? '').replace(REMARK_CONTROL, '').trim()

/** Who did it, for the audit trail: the verified caller, with their name as stored in the users table. */
async function actorOf(caller, deps) {
  const row = await deps.userRows.get(caller.id)
  return { role: caller.role, id: caller.id, name: String(row?.name ?? caller.account.name ?? '').trim().slice(0, 128) || null }
}

/**
 * Moves a complaint to a new status, records WHO did it and WHEN (history entry + "last updated" on the complaint),
 * keeps an optional PUBLIC remark for the student, and notifies the student. Internal notes do NOT go through here: they
 * belong in complaint_notes. `actor` = { role: 'department' | 'admin', id, name }.
 *   expectedStatus      – the status the user saw; a different current status means someone else changed it (409)
 *   requireResolveRemark – marking resolved needs a remark (the department tells the student what was done)
 * Authorization (who may change which complaint) is the caller's job; this checks the move itself. Throws HttpError.
 */
export async function recordStatusChange(deps, { complaintId, status, remark, actor, expectedStatus, requireResolveRemark = false }) {
  if (!STATUSES.includes(status)) throw invalid({ status: 'Choose a valid status.' })
  if (remark !== undefined && remark !== null && typeof remark !== 'string') throw invalid({ remark: 'The remark must be text.' })
  const cleanedRemark = cleanRemark(remark)
  if (cleanedRemark.length > RULES.remark.max) throw invalid({ remark: `The remark must be at most ${RULES.remark.max} characters.` })
  if (!['department', 'admin'].includes(actor?.role)) throw new HttpError(403, 'forbidden', 'You do not have permission to do that.')

  const row = await deps.complaints.get(complaintId)
  if (!row) throw new HttpError(404, 'not_found', 'That complaint was not found.')
  if (expectedStatus && row.status !== expectedStatus) {
    throw new HttpError(409, 'stale_status', 'This complaint was updated by someone else. Reload it and try again.')
  }
  const allowed = TRANSITIONS[row.status] ?? []
  if (!allowed.includes(status)) {
    throw new HttpError(409, 'invalid_transition', `A complaint that is "${row.status}" cannot move to "${status}".`, { status: 'This status change is not allowed.' })
  }
  if (requireResolveRemark && status === 'resolved' && cleanedRemark.length < RULES.resolveRemarkMin) {
    throw invalid({ remark: `Explain what was done (at least ${RULES.resolveRemarkMin} characters) before marking this complaint resolved.` })
  }

  const now = clock(deps)
  const stamp = now.toISOString()
  const previousStatus = row.status
  const updated = await deps.complaints.update(complaintId, {
    status,
    lastUpdatedBy: actor.id ?? null,
    lastUpdatedByName: actor.name ?? null,
    lastUpdatedAt: stamp,
    ...(status === 'resolved' ? { resolvedAt: stamp } : {}),
  })
  try {
    await deps.history.create(
      {
        complaintId,
        kind: 'status',
        status,
        previousStatus,
        ...(cleanedRemark ? { remark: cleanedRemark } : {}),
        actorRole: actor.role,
        actorId: actor.id ?? null,
        actorName: actor.name ?? null,
        changedAt: stamp,
      },
      complaintPermissions(),
    )
  } catch (error) {
    // Never leave a status change without its timeline entry: put the old values back.
    await deps.complaints
      .update(complaintId, {
        status: previousStatus,
        resolvedAt: row.resolvedAt ?? null,
        lastUpdatedBy: row.lastUpdatedBy ?? null,
        lastUpdatedByName: row.lastUpdatedByName ?? null,
        lastUpdatedAt: row.lastUpdatedAt ?? null,
      })
      .catch((e) => deps.log?.(`rollback failed for ${complaintId}: ${e?.message ?? e}`))
    throw error
  }

  await notify.statusChanged(deps, row, { status, remark: cleanedRemark, stamp })
  return { complaint: updated, previousStatus }
}

