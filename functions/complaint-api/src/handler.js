/** No legitimate request is anywhere near this size (the longest field is a 5000-character description). */
export const MAX_BODY_CHARS = 64 * 1024

function parseBody(req) {
  const isObject = (value) => value && typeof value === 'object' && !Array.isArray(value)
  if (isObject(req.bodyJson)) {
    if (JSON.stringify(req.bodyJson).length > MAX_BODY_CHARS) throw new HttpError(413, 'payload_too_large', 'That request is too large.')
    return req.bodyJson
  }
  const text = req.bodyText ?? (typeof req.body === 'string' ? req.body : '')
  if (text.length > MAX_BODY_CHARS) throw new HttpError(413, 'payload_too_large', 'That request is too large.')
  try {
    const parsed = JSON.parse(text || '{}')
    if (isObject(parsed)) return parsed
  } catch {
    /* fall through */
  }
  throw new HttpError(400, 'invalid_request', 'Request body must be a JSON object.')
}

async function authenticate(req, deps) {
  const headers = req.headers ?? {}
  const userId = headers['x-appwrite-user-id']
  const jwt = headers['x-appwrite-user-jwt']
  if (!userId || !jwt) throw new HttpError(401, 'unauthenticated', 'You must be signed in.')
  let verifiedId
  try {
    verifiedId = await deps.verifyJwt(jwt)
  } catch {
    throw new HttpError(401, 'unauthenticated', 'Your session is not valid. Please sign in again.')
  }
  if (verifiedId !== userId) throw new HttpError(401, 'unauthenticated', 'Your session is not valid. Please sign in again.')
  const account = await deps.users.get(userId)
  if (!account) throw new HttpError(401, 'unauthenticated', 'Your session is not valid. Please sign in again.')
  if (account.status === false) throw new HttpError(403, 'account_disabled', 'This account has been disabled. Contact the administrator.')
  return { id: userId, account, role: roleFromLabels(account.labels) }
}

const clock = (deps) => (deps.now ? deps.now() : new Date())

/* ------------------------------------------------------------------ *
 * Attachment verification
 * ------------------------------------------------------------------ */

/**
 * The browser uploads the file straight to Storage (that is the only way to send bytes), so the file is
 * UNTRUSTED until checked here. Name, size and type are read from the stored file, never from the request.
 */
async function verifyAttachment(fileId, caller, deps) {
  const bad = (message) => invalid({ attachment: message })
  const file = await deps.files.get(fileId)
  if (!file) throw bad('The attachment could not be found. Please upload it again.')

  const perms = file.$permissions ?? []
  // Only the uploader holds delete rights on a fresh upload; an already-attached file has been locked (no delete).
  if (!perms.includes(`delete("user:${caller.id}")`)) throw bad('This attachment cannot be used. Please upload your own file again.')

  const size = Number(file.sizeOriginal ?? file.size ?? 0)
  if (!(size > 0)) throw bad('The attachment is empty.')
  if (size > RULES.attachment.maxBytes) throw bad(`The attachment must be smaller than ${RULES.attachment.maxBytes / 1024 / 1024} MB.`)

  const extension = fileExtension(file.name)
  const expectedMime = RULES.attachment.types[extension]
  if (!expectedMime) throw bad(`Only ${Object.keys(RULES.attachment.types).join(', ').toUpperCase()} files are allowed.`)
  // Appwrite detects the MIME type from the file's content: a renamed .exe cannot pass as .pdf.
  if (String(file.mimeType ?? '').toLowerCase() !== expectedMime) throw bad('The file contents do not match its type. Upload a real image or PDF.')

  return { id: file.$id, name: safeFileName(file.name), mimeType: expectedMime, size }
}

/* ------------------------------------------------------------------ *
 * Action: complaint.submit
 * ------------------------------------------------------------------ */

async function actionSubmit(caller, body, deps) {
  if (caller.role !== ROLES.STUDENT) throw new HttpError(403, 'students_only', 'Only students can submit complaints.')
  const input = validateSubmission(body) // client-supplied studentId / departmentId / status / dates are never read

  // The category decides the department. Both must exist and be active.
  const category = await deps.categories.get(input.categoryId)
  if (!category || category.status !== 'active') throw invalid({ categoryId: 'That category is not available. Choose another one.' })
  const department = await deps.departments.get(category.departmentId)
  if (!department || department.status !== 'active') throw invalid({ categoryId: 'That category is not available right now. Choose another one.' })

  const userRow = await deps.userRows.get(caller.id)
  if (userRow?.accountStatus === 'disabled') throw new HttpError(403, 'account_disabled', 'This account has been disabled. Contact the administrator.')

  // Double-click / retry safety, and a simple spam limit, both from the student's recent complaints.
  const now = clock(deps)
  const recent = await deps.complaints.listByStudent(caller.id, 25)
  const age = (row) => now.getTime() - new Date(row.submittedAt).getTime()
  const sameContent = (row) => row.title === input.title && row.description === input.description && row.categoryId === input.categoryId
  const duplicate = recent.find((row) => sameContent(row) && age(row) < RULES.duplicateWindowMinutes * 60_000)
  if (duplicate) return { complaint: toStudentView(duplicate), duplicate: true }
  const inWindow = recent.filter((row) => age(row) < RULES.rateLimit.windowMinutes * 60_000).length
  if (inWindow >= RULES.rateLimit.max) {
    throw new HttpError(429, 'too_many_submissions', `You have submitted several complaints in a short time. Please wait a few minutes and try again.`)
  }

  const attachment = input.attachmentId ? await verifyAttachment(input.attachmentId, caller, deps) : null
  if (attachment) await deps.files.lock(attachment.id, lockedFilePermissions(caller.id))

  const data = {
    studentId: caller.id,
    studentName: String(userRow?.name ?? caller.account.name ?? '').trim() || 'Student',
    studentRollNumber: userRow?.rollNumber ?? null,
    title: input.title,
    description: input.description,
    location: input.location,
    categoryId: category.$id,
    categoryName: category.name,
    departmentId: department.$id,
    departmentName: department.name,
    status: INITIAL_STATUS,
    priority: 'medium',
    submittedAt: now.toISOString(),
    attachmentId: attachment?.id ?? null,
    attachmentName: attachment?.name ?? null,
    attachmentMime: attachment?.mimeType ?? null,
    attachmentSize: attachment?.size ?? null,
  }

  // Unique ID: random suffix + the database's unique row ID. On the (very unlikely) clash, try a new one.
  let row
  for (let attempt = 0; attempt < MAX_ID_ATTEMPTS && !row; attempt++) {
    const reference = generateReference(now, deps.randomChars?.(attempt))
    try {
      row = await deps.complaints.create(reference, { ...data, referenceNumber: reference }, complaintPermissions())
    } catch (error) {
      if (!isConflict(error)) throw error
    }
  }
  if (!row) throw new HttpError(503, 'id_unavailable', 'Could not create your complaint right now. Please try again.')

  // First timeline entry. Best effort: without it the timeline is rebuilt from submittedAt (see buildTimeline).
  try {
    await deps.history.create({ complaintId: row.$id, status: INITIAL_STATUS, actorRole: 'system', changedAt: now.toISOString() }, complaintPermissions())
  } catch (error) {
    deps.log?.(`could not write the first history entry for ${row.$id}: ${error?.message ?? error}`)
  }

  // Ask the AI analysis to analyse the stored complaint. Asynchronous and best effort: the student never waits for it, and if it
  // cannot be started staff can run it from the complaint page. The complaint is already saved.
  try {
    await deps.ai.trigger(row.$id, { force: false })
  } catch (error) {
    deps.log?.(`could not start AI analysis for ${row.$id}: ${error?.message ?? error}`)
  }

  // Notifications (never throw): a confirmation for the student and a heads-up for the department's staff.
  await notify.complaintSubmitted(deps, row)

  return { complaint: toStudentView(row), duplicate: false }
}

