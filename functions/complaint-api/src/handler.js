export const RULES = {
  title: { min: 5, max: 150 },
  description: { min: 10, max: 5000 },
  location: { max: 300 },
  attachment: {
    maxBytes: 5 * 1024 * 1024,
    types: { jpg: 'image/jpeg', jpeg: 'image/jpeg', png: 'image/png', pdf: 'application/pdf' },
  },
  rateLimit: { max: 5, windowMinutes: 10 },
  duplicateWindowMinutes: 2,
  search: { max: 100 },
  remark: { max: 1000 },
  note: { max: 2000 },
  resolveRemarkMin: 5,
}

