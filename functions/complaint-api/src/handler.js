/**
 * complaint-api – trusted backend logic for student complaints (Phase 8) and complaint history/tracking (Phase 9).
 *
 * Runs inside an Appwrite Function with a server API key. It is the ONLY code that creates complaint rows.
 * The browser sends WHAT the student typed (title, description, location, category, attachment file ID);
 * everything that must be trusted is decided here:
 *   - WHO the student is        -> from the verified login (JWT), never from the request body
 *   - WHICH department          -> looked up from the category in the database
 *   - the initial status, dates -> set by the server
 *   - the complaint ID          -> generated by the server (unique)
 *   - who may read the complaint-> row permissions: the complainant and administrators only;
 *                                  department staff get it through the actions below, filtered by their assignments.
 * Any studentId / departmentId / status / date in the request body is ignored.
 *
 * Phase 9: students never read complaint rows directly. They list, search and open their complaints through the
 * actions below, which return an explicit whitelist of fields (no priority, assigned staff, internal notes, staff IDs).
 *
 * Pure logic with injected dependencies (`deps`), so it is fully testable. See main.js for the real wiring.
 */
import { randomInt } from 'node:crypto'

