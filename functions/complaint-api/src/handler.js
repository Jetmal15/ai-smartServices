/* ------------------------------------------------------------------ *
 * AI analysis review (Phase 11). The AI only SUGGESTS. A person with authority decides:
 *   - staff of the complaint's department, or an administrator, may review a suggestion and apply the suggested PRIORITY;
 *   - only an administrator may move a complaint to another category/department.
 * The values applied always come from the stored suggestion or the administrator's own choice, validated here – never
 * from the browser's idea of what the AI said.
 * ------------------------------------------------------------------ */

function requireReviewer(caller) {
  if (caller.role !== ROLES.DEPARTMENT && caller.role !== ROLES.ADMIN) throw new HttpError(403, 'forbidden', 'You do not have permission to do that.')
}

async function completedAnalysis(row, deps) {
  const stored = await deps.aiSummaries.get(row.$id)
  if (!stored || stored.status !== 'completed') throw new HttpError(409, 'no_analysis', 'There is no completed AI analysis for this complaint yet.')
  return stored
}

/** Start (or re-run) the AI analysis. The result appears on the complaint page when it is ready. */
async function actionAiAnalyze(caller, body, deps) {
  requireReviewer(caller)
  const row = await loadVisibleComplaint(caller, body, deps)
  const stored = await deps.aiSummaries.get(row.$id)
  if ((stored?.attempts ?? 0) >= AI_MAX_ATTEMPTS) throw new HttpError(429, 'too_many_analyses', 'This complaint has been analysed too many times.')
  try {
    await deps.ai.trigger(row.$id, { force: true })
  } catch (error) {
    deps.log?.(`could not start AI analysis for ${row.$id}: ${error?.message ?? error}`)
    throw new HttpError(503, 'ai_unavailable', 'The analysis service could not be reached. Try again later.')
  }
  return { ...(await staffDetail(await deps.complaints.get(row.$id), deps)), queued: true }
}

/** Record that a person reviewed the AI suggestion (accepted or dismissed). Changes nothing about the complaint itself. */
async function actionAiReview(caller, body, deps) {
  requireReviewer(caller)
  const row = await loadVisibleComplaint(caller, body, deps)
  if (!['accepted', 'dismissed'].includes(body.decision)) throw invalid({ decision: 'Choose accept or dismiss.' })
  await completedAnalysis(row, deps)
  const actor = await actorOf(caller, deps)
  await deps.aiSummaries.update(row.$id, { reviewStatus: body.decision, reviewedBy: actor.id, reviewedByName: actor.name, reviewedAt: clock(deps).toISOString() })
  return staffDetail(row, deps)
}

